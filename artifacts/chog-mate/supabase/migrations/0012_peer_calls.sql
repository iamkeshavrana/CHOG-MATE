alter table public.calls
  drop constraint if exists calls_status_check;

alter table public.calls
  add constraint calls_status_check
    check (status in ('calling', 'connecting', 'connected', 'ended', 'rejected', 'missed', 'failed')),
  add column if not exists last_activity_at timestamptz not null default now();

create unique index if not exists calls_one_active_call_per_match
  on public.calls (match_id)
  where status in ('calling', 'connecting', 'connected');

create index if not exists calls_active_caller_idx
  on public.calls (caller_id, status, started_at desc);

create index if not exists calls_active_receiver_idx
  on public.calls (receiver_id, status, started_at desc);

create table if not exists public.call_signals (
  id bigint generated by default as identity primary key,
  call_id uuid not null references public.calls(id) on delete cascade,
  sender_id uuid not null references public.users(id) on delete cascade,
  signal_type text not null check (signal_type in ('offer', 'answer', 'ice_candidate')),
  payload jsonb not null check (
    jsonb_typeof(payload) = 'object'
    and octet_length(payload::text) <= 24000
  ),
  created_at timestamptz not null default now()
);

alter table public.call_signals enable row level security;
revoke all on table public.call_signals from public, anon, authenticated;
grant all privileges on table public.call_signals to service_role;
grant usage, select on sequence public.call_signals_id_seq to service_role;

create index if not exists call_signals_poll_idx
  on public.call_signals (call_id, id);

create or replace function public.create_peer_call(
  p_match_id uuid,
  p_caller_id uuid,
  p_receiver_id uuid,
  p_type text
) returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_call_id uuid;
  v_lock_user text;
begin
  if p_caller_id = p_receiver_id or p_type not in ('audio', 'video') then
    return null;
  end if;

  for v_lock_user in
    select user_id::text
    from unnest(array[p_caller_id, p_receiver_id]) as participants(user_id)
    order by user_id
  loop
    perform pg_advisory_xact_lock(hashtextextended(v_lock_user, 0));
  end loop;

  perform 1
  from public.matches m
  where m.id = p_match_id
    and m.status = 'active'
    and (
      (m.user_a = p_caller_id and m.user_b = p_receiver_id)
      or (m.user_a = p_receiver_id and m.user_b = p_caller_id)
    )
  for update;

  if not found or exists (
    select 1
    from public.blocks b
    where (b.blocker_id = p_caller_id and b.blocked_user_id = p_receiver_id)
       or (b.blocker_id = p_receiver_id and b.blocked_user_id = p_caller_id)
  ) then
    return null;
  end if;

  if exists (
    select 1
    from public.calls c
    where c.status in ('calling', 'connecting', 'connected')
      and (
        c.caller_id in (p_caller_id, p_receiver_id)
        or c.receiver_id in (p_caller_id, p_receiver_id)
      )
  ) then
    return null;
  end if;

  insert into public.calls (
    match_id,
    caller_id,
    receiver_id,
    type,
    status,
    started_at,
    last_activity_at
  ) values (
    p_match_id,
    p_caller_id,
    p_receiver_id,
    p_type,
    'calling',
    now(),
    now()
  )
  returning id into v_call_id;

  return v_call_id;
end;
$$;

revoke all on function public.create_peer_call(uuid, uuid, uuid, text) from public, anon, authenticated;
grant execute on function public.create_peer_call(uuid, uuid, uuid, text) to service_role;
